"""Verbatim before/after examples for the report and the video, picked by rule from committed run files.
Usage: examples.py RUN.jsonl [--n 3] [--seed 0] [--out hackathon/report/EXAMPLES.md]

For each gate failure kind (G1 invented, G2 lost, G4 gutted) it takes a seeded random item that fails that gate,
and prints the draft, the output and the problems hackathon/harness/gates.py names. Nothing is edited or chosen
by hand, so the examples can't be cherry-picked.
"""
from __future__ import annotations

import argparse, json, os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "../.."))
sys.path[:0] = [HERE, os.path.join(ROOT, "hackathon/harness")]
import gates as gt  # noqa: E402
import score_all as sa  # noqa: E402

KINDS = (("g1_nothing_invented", "G1: invented a fact"), ("g2_nothing_lost", "G2: lost a fact"),
         ("g4_not_gutted", "G4: cut too much"))


def pick(run: str, n_per_kind: int, seed: int) -> list[dict]:
    items = sa.all_items()
    rows = [r for r in sa.read_jsonl(run) if r["id"] in items]
    checked = [(r, gt.check(items[r["id"]]["ai_draft"], r["output"])) for r in sorted(rows, key=lambda r: r["id"])]
    rng, out, used = random.Random(seed), [], set()
    for key, title in KINDS:
        pool = [(r, g) for r, g in checked if not g[key] and r["id"] not in used]
        for r, g in rng.sample(pool, min(n_per_kind, len(pool))):
            used.add(r["id"])
            out.append({"kind": title, "id": r["id"], "system": r["system"], "draft": items[r["id"]]["ai_draft"],
                        "output": r["output"], "problems": g["problems"], "pool": len(pool)})
    return out


def render(examples: list[dict], run: str) -> str:
    lines = ["# Failure examples", "", f"_Generated by `hackathon/eval/examples.py` from `{sa.rel(run)}`: one seeded "
             "random item per gate failure kind. Verbatim, not edited._", ""]
    for e in examples:
        lines += [f"## {e['kind']} ({e['id']}, `{e['system']}`; {e['pool']} items fail this gate)", "",
                  "**Draft**", "", "> " + e["draft"].replace("\n", "\n> "), "",
                  "**Output**", "", "> " + e["output"].replace("\n", "\n> "), "",
                  "**What the gates found**", ""] + [f"- {p}" for p in e["problems"]] + [""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--n", type=int, default=1)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=os.path.join(ROOT, "hackathon/report/EXAMPLES.md"))
    a = ap.parse_args(argv)
    ex = pick(a.run, a.n, a.seed)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(ex, a.run))
    print(f"{len(ex)} examples -> {sa.rel(a.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
