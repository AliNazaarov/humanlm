"""Build data.js for the FeatherLM editor page (hackathon/demo/app/index.html).

Examples are a seeded random sample of eval items (not picked by result), each with the committed
O3c rewrite (our entry), the committed frontier-strong Claude rewrite, and the real gate results for
both from hackathon/harness/gates.py. The slop phrase list ships too, so the page can mark AI tells
in any text the reader pastes.

    PYTHONUTF8=1 python hackathon/demo/app/build_app_data.py
"""
import json, os, random, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
sys.path.insert(0, os.path.join(ROOT, "hackathon/harness"))
sys.path.insert(0, os.path.join(ROOT, "pipeline"))
import gates  # noqa: E402
import metrics as m  # noqa: E402

OURS = "evals/runs/hack_O3c_glm_prompt_harness_style.jsonl"
CLAUDE = "evals/runs/hack_strong_claude-opus-5-5.jsonl"
N, SEED = 8, 20261102


def rows(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return {r["id"]: r for r in map(json.loads, f)}


LABELS = {"dev-016": "Pricing page", "dev-021": "Integrations page", "dev-054": "Launch post",
          "dev-073": "Social post", "dev-081": "Search ad"}


def kind(i, draft):
    if i in LABELS:
        return LABELS[i]
    head = draft.lstrip().split("\n", 1)[0].lower()
    for key, label in (("subject:", "Email"), ("headline:", "Landing page"), ("primary text:", "Ad"),
                       ("tagline:", "Launch post"), ("title:", "Listing")):
        if head.startswith(key):
            return label
    return "Post"


def main():
    items = rows("evals/eval_all.jsonl")
    ours, claude = rows(OURS), rows(CLAUDE)
    ids = sorted(i for i in items if i in ours and i in claude and items[i]["id"].startswith("dev-"))
    pick = sorted(random.Random(SEED).sample(ids, N))
    out = []
    for i in pick:
        d = items[i]["ai_draft"]
        f = m.faithfulness(d, ours[i]["output"])
        out.append({
            "id": i, "kind": kind(i, d), "draft": d,
            "feather": ours[i]["output"], "claude": claude[i]["output"],
            "feather_gates": gates.check(d, ours[i]["output"]),
            "claude_gates": gates.check(d, claude[i]["output"]),
            "numbers": sorted(m._numbers(d)),
            "feather_latency_ms": ours[i]["latency_ms"],
            "names_kept": f["names_kept"],
        })
    phrases = m.load_phrases()
    data = {"source": {"ours": OURS, "claude": CLAUDE, "seed": SEED, "headline": "hackathon/report/results.json"},
            "examples": out, "phrases": phrases}
    dst = os.path.join(os.path.dirname(__file__), "data.js")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by build_app_data.py. Do not edit.\nwindow.FEATHER_DATA = ")
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write(";\n")
    for e in out:
        print(e["id"], e["kind"], "feather", e["feather_gates"]["pass"], "claude", e["claude_gates"]["pass"])


if __name__ == "__main__":
    main()
